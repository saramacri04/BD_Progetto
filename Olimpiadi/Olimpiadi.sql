CREATE TABLE Nazione (
  Codice_ISO CHAR(3) PRIMARY KEY,
  Nome VARCHAR(100) NOT NULL,
  Continente VARCHAR(50) NOT NULL,
  Capitale VARCHAR(100) NOT NULL,
  Popolazione BIGINT CHECK (Popolazione>0) NOT NULL
);

CREATE TABLE Squadra (
  Codice_ISO CHAR(3),
  Genere CHAR(1) CHECK (Genere IN ('M','F')),
  Qualificazione VARCHAR(30) CHECK (Qualificazione IN (
     'Paese Organizzatore',
     'FIVB World Rankings',
     'Torneo di Qualificazione'
  )),
  N_Trofei INT,
  PRIMARY KEY (Codice_ISO, Genere),
  FOREIGN KEY (Codice_ISO) REFERENCES Nazione(Codice_ISO)
);

CREATE TABLE Persona (
  Codice_Fiscale CHAR(17) PRIMARY KEY,
  Codice_ISO CHAR(3) NOT NULL,
  Genere CHAR(1) NOT NUll, 
  Nome VARCHAR(50) NOT NULL,
  Cognome VARCHAR(50) NOT NULL,
  Data_Nascita DATE NOT NULL,
  FOREIGN KEY (Codice_ISO, Genere) REFERENCES Squadra(Codice_ISO, Genere)
);

CREATE TABLE Allenatore (
    Codice_Fiscale CHAR(17) PRIMARY KEY,
    Anni_Esperienza INT CHECK (Anni_Esperienza>=0) NOT NULL,
    Ruolo VARCHAR(30) NOT NULL,
    FOREIGN KEY (Codice_Fiscale) REFERENCES Persona(Codice_Fiscale)
);

CREATE TABLE Giocatore (
  Codice_Fiscale CHAR(17) PRIMARY KEY,
  N_Maglia INT NOT NULL,
  Altezza INT NOT NULL CHECK (Altezza>0), 
  Peso INT NOT NULL  CHECK (Peso>0), 
  Ruolo VARCHAR(10) NOT NULL CHECK (Ruolo IN (
    'Banda','Opposto','Libero','Centrale','Alzatore'
  )),
  FOREIGN KEY (Codice_Fiscale) REFERENCES Persona(Codice_Fiscale)
);

CREATE TABLE Infortunio (
  Tipologia VARCHAR(100),
  Parte_Corpo VARCHAR(100),
  Operazione BOOLEAN NOT NULL,
  PRIMARY KEY (Tipologia, Parte_Corpo)
);

CREATE TABLE Subisce (
    Codice_Fiscale VARCHAR(17),
    Tipologia VARCHAR(100),
    Parte_Corpo VARCHAR(100),
    Data DATE,
    Tempo_Recupero INT NOT NULL,
    PRIMARY KEY (Codice_Fiscale, Tipologia, Parte_Corpo, Data),
    FOREIGN KEY (Codice_Fiscale) REFERENCES Giocatore(Codice_Fiscale),
    FOREIGN KEY (Tipologia, Parte_Corpo) REFERENCES Infortunio(Tipologia, Parte_Corpo)
);

CREATE TABLE Palazzetto (
  Indirizzo VARCHAR(255) PRIMARY KEY,
  Nome VARCHAR(100) NOT NULL,
  Capienza INT NOT NULL,
  Anno_Costruzione INT NOT NULL
);

CREATE TABLE Partita (
    Data DATE,
    Squadra1 CHAR(3) NOT NULL,
    Squadra2 CHAR(3) NOT NULL,
    Genere CHAR(1) NOT NULL,       
    Fase VARCHAR(50) NOT NULL,
    Risultato VARCHAR(10) NOT NULL,
    Indirizzo VARCHAR(255) NOT NULL,
    PRIMARY KEY (Data, Squadra1, Squadra2, Genere),
    FOREIGN KEY (Indirizzo) REFERENCES Palazzetto(Indirizzo),
    FOREIGN KEY (Squadra1, Genere) REFERENCES Squadra(Codice_ISO,Genere),
    FOREIGN KEY (Squadra2,Genere) REFERENCES Squadra(Codice_ISO,Genere)
);

CREATE TABLE SET (
    N_Set INT,
    Data DATE NOT NULL,
    Squadra1 CHAR(3) NOT NULL,
    Squadra2 CHAR(3) NOT NULL,
    Genere CHAR(1) NOT NULL,    
    Punteggio_1 INT NOT NULL CHECK (Punteggio_1 >= 0),
    Punteggio_2 INT NOT NULL CHECK (Punteggio_2 >= 0),
    PRIMARY KEY (N_Set, Data, Squadra1, Squadra2, Genere),
    FOREIGN KEY (Data, Squadra1, Squadra2, Genere) REFERENCES Partita(Data, Squadra1, Squadra2, Genere),
    CHECK (Squadra1 <> Squadra2)
);

CREATE TABLE Statistica (
  Data DATE NOT NULL,
  Squadra1 CHAR(3) NOT NULL,
  Squadra2 CHAR(3) NOT NULL,
  Genere CHAR(1) NOT NULL,             
  MVP CHAR(17) NOT NULL,     
  Attack_Efficiency INT NOT NULL,    
  Block_Efficiency INT NOT NULL,       
  Dig_Efficiency INT NOT NULL,   
  Service_Efficiency INT NOT NULL, 
  PRIMARY KEY (Data, Squadra1, Squadra2, Genere),
  FOREIGN KEY (Data, Squadra1, Squadra2, Genere) REFERENCES Partita(Data, Squadra1, Squadra2, Genere),
  FOREIGN KEY (MVP) REFERENCES Giocatore(Codice_Fiscale)
);

